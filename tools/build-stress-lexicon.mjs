#!/usr/bin/env node
/* build-stress-lexicon — the forms whose stress the engine's rules get wrong, with pealim's stress.
 *
 *   node tools/build-stress-lexicon.mjs <pages-dir> [--exclude <slugs.txt>] [--write]
 *
 * 06.10.2026. Some forms are written alike with two stresses (תַּסְגִּירִי a verb, תַּלְמִידִי a noun ;
 * קָמוּ and קָנוּ). No rule on the niqqud can split them, so translit.js consults a lexicon
 * (setStressLexicon, data/stress-lexicon.json). This tool writes it, and nothing else does.
 *
 * Source: saved pealim entry pages (<pages-dir>/*.html), one per entry. For every conjugation or
 * declension cell, pealim prints the pointed form and a transcription whose bold syllable is the
 * stress. The engine reads the form with an EMPTY lexicon; when its stress differs from pealim's,
 * the form enters the lexicon with pealim's stress, counted from the end (1 = final).
 * Skipped: a form whose syllables the engine counts differently from pealim (the furtive patah,
 * the 2fs past), since the two stresses cannot be compared; and a form two entries give two
 * different stresses (a true homograph), since the lexicon could only pick one.
 * --exclude: slugs kept OUT of the lexicon, so that a bench can measure the lexicon on entries it
 * never saw. Without --write, the tool reports and writes nothing. */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'data', 'stress-lexicon.json');
const args = process.argv.slice(2);
const dir = args.find((a) => !a.startsWith('--') && args[args.indexOf(a) - 1] !== '--exclude');
if (!dir || !fs.existsSync(dir)) { console.error('usage: build-stress-lexicon.mjs <pages-dir> [--exclude slugs.txt] [--write]'); process.exit(2); }
const exI = args.indexOf('--exclude');
const exclude = new Set(exI >= 0 ? fs.readFileSync(args[exI + 1], 'utf8').split(/\s+/).filter(Boolean) : []);
const WRITE = args.includes('--write');

const T = createRequire(import.meta.url)(path.join(ROOT, 'assets', 'translit.js'));
T.setStressLexicon({});
const runs = (s) => (s.match(/[aeiou]+/g) || []).length;

const found = new Map();          // form -> Set of stresses
let cells = 0, compared = 0, entries = 0;
for (const f of fs.readdirSync(dir).filter((x) => x.endsWith('.html')).sort()) {
  if (exclude.has(f.replace(/\.html$/, ''))) continue;
  entries++;
  const html = fs.readFileSync(path.join(dir, f), 'utf8');
  for (const m of html.matchAll(/<span class="menukad">([^<]+)<\/span><\/div><div class="transcription">(.*?)<\/div>/g)) {
    cells++;
    const he = m[1].replace(/&rlm;|[!‏]/g, '').normalize('NFC').trim();
    const tr = m[2].replace(/&rlm;|!/g, '');
    if (!he || /\s|־/.test(he) || !/<b>/.test(tr)) continue;
    const n = runs(tr.replace(/<\/?b>/g, ''));
    if (n < 2) continue;
    /* Deux voyelles qui se touchent (hors diphtongues ai, ei, oi, ui) : pealim ecrit le patah
       furtif collé (« lehitga'agea »), et le compte par groupes de voyelles y voit une syllabe
       de moins. לְהִתְגַּעְגֵּעַ est entre au lexique avec un accent faux avant ce filtre. */
    if (/[aeiou]{2,}/.test(tr.replace(/<\/?b>/g, '').replace(/[aeou]i/g, 'X'))) continue;
    const want = n - (runs(tr.split('<b>')[0]) + 1) + 1;
    const syl = T.transliterate(he).split('-');
    if (syl.length !== n) continue;
    compared++;
    const got = syl.length - syl.findIndex((x) => /[A-Z]/.test(x));
    const set = found.get(he) || new Set();
    set.add(want === got ? 0 : want);   // 0 = the rules already agree
    found.set(he, set);
  }
}
const lexicon = {};
let homographs = 0;
for (const [he, set] of found) {
  if (set.size > 1) { homographs++; continue; }
  const [v] = set;
  if (v) lexicon[he] = v;
}
const keys = Object.keys(lexicon).sort();
console.log(`${entries} fiches, ${cells} cases, ${compared} comparables, ${found.size} formes distinctes`);
console.log(`${keys.length} formes au lexique (les regles se trompent), ${homographs} homographes ecartes`);
if (!WRITE) { console.log('(rapport seulement : --write pour ecrire)'); process.exit(0); }
const out = { _comment: 'GENERATED by tools/build-stress-lexicon.mjs from pealim entry pages, ' + new Date().toISOString().slice(0, 10)
  + '. Key = NFC pointed form. Value = stressed syllable counted from the END (1 = final), pealim\'s bold syllable. Only forms the rules in translit.js get wrong. Do not edit by hand; do not tune the rules on it.' };
for (const k of keys) out[k] = lexicon[k];
fs.writeFileSync(OUT, JSON.stringify(out) + '\n');
console.log('ecrit : ' + OUT + ' (' + fs.statSync(OUT).size + ' octets)');
